import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const worldAtlas = require("world-atlas/countries-50m.json");

const MAP_SCALE_X = 1.68;
const MAP_SCALE_Z = 1.24;
const MIN_LATITUDE = -82;
const MAX_LATITUDE = 82;
const CELL_SIZE = 12;
const POINT_STRIDE = 5;
const QUANTIZATION = 100;

const KINDS = [
  "broadleaf",
  "pine",
  "cypress",
  "palm",
  "acacia",
  "townhouse",
  "villa",
  "chalet",
  "adobe",
  "dune",
  "rock",
  "mountain-green",
  "mountain-dry",
  "mountain-alpine",
  "meadow-lush",
  "meadow-dry",
  "field-green",
  "field-gold",
];

const KIND = Object.fromEntries(KINDS.map((name, index) => [name, index]));
const topology = worldAtlas;
const countries = feature(
  topology,
  topology.objects.countries,
).features;

const landRings = countries.flatMap((country) =>
  geometryToOuterRings(country.geometry).map((ring) => {
    const longitudes = ring.map((point) => point[0]);
    const latitudes = ring.map((point) => point[1]);
    return {
      ring,
      minLongitude: Math.min(...longitudes),
      maxLongitude: Math.max(...longitudes),
      minLatitude: Math.min(...latitudes),
      maxLatitude: Math.max(...latitudes),
    };
  }),
);

const minimumX = -180 * MAP_SCALE_X;
const maximumX = 180 * MAP_SCALE_X;
const minimumZ = -latitudeToMercator(MAX_LATITUDE) * MAP_SCALE_Z;
const maximumZ = -latitudeToMercator(MIN_LATITUDE) * MAP_SCALE_Z;
const cellCountX = Math.ceil((maximumX - minimumX) / CELL_SIZE);
const cellCountZ = Math.ceil((maximumZ - minimumZ) / CELL_SIZE);
const packed = [];

for (let cellZ = 0; cellZ < cellCountZ; cellZ += 1) {
  for (let cellX = 0; cellX < cellCountX; cellX += 1) {
    const random = mulberry32(hashCell(cellX, cellZ));
    for (let localZ = 0; localZ < 3; localZ += 1) {
      for (let localX = 0; localX < 3; localX += 1) {
        const x =
          minimumX +
          cellX * CELL_SIZE +
          (localX + 0.5) * (CELL_SIZE / 3) +
          (random() - 0.5) * 1.25;
        const z =
          minimumZ +
          cellZ * CELL_SIZE +
          (localZ + 0.5) * (CELL_SIZE / 3) +
          (random() - 0.5) * 1.25;
        if (x > maximumX || z > maximumZ) {
          continue;
        }

        const longitude = x / MAP_SCALE_X;
        const latitude = mercatorToLatitude(-z / MAP_SCALE_Z);
        if (!isLand(longitude, latitude)) {
          continue;
        }

        const biome = sampleBiome(longitude, latitude);
        const kind = choosePrimaryKind(biome, latitude, random);
        addPoint(kind, x, z, random, primaryScale(kind, random));

        if (isTree(kind) && random() < 0.62) {
          const angle = random() * Math.PI * 2;
          const distance = 0.42 + random() * 0.58;
          const clusterX = x + Math.cos(angle) * distance;
          const clusterZ = z + Math.sin(angle) * distance;
          const clusterLongitude = clusterX / MAP_SCALE_X;
          const clusterLatitude = mercatorToLatitude(-clusterZ / MAP_SCALE_Z);
          if (isLand(clusterLongitude, clusterLatitude)) {
            addPoint(kind, clusterX, clusterZ, random, 0.5 + random() * 0.24);
          }
        }

        const patchRoll = random();
        if (
          biome.desert < 0.42 &&
          biome.mountain < 0.58 &&
          Math.abs(latitude) < 62
        ) {
          if (patchRoll < 0.055) {
            addPoint(
              biome.humidity > 0.46 ? "field-green" : "field-gold",
              x + (random() - 0.5) * 1.6,
              z + (random() - 0.5) * 1.6,
              random,
              0.7 + random() * 0.32,
            );
          } else if (patchRoll < 0.16) {
            addPoint(
              biome.humidity > 0.42 ? "meadow-lush" : "meadow-dry",
              x + (random() - 0.5) * 1.8,
              z + (random() - 0.5) * 1.8,
              random,
              0.62 + random() * 0.32,
            );
          }
        }
      }
    }
  }
}

const output = `/*
 * Generated by scripts/generate-world-ecology.mjs.
 * Do not hand-edit: regenerate with \`npm run generate:ecology\`.
 *
 * Tuple layout: kind, x * ${QUANTIZATION}, z * ${QUANTIZATION}, rotation byte, scale * ${QUANTIZATION}.
 */
export const WORLD_ECOLOGY_CELL_SIZE = ${CELL_SIZE};
export const WORLD_ECOLOGY_POINT_STRIDE = ${POINT_STRIDE};
export const WORLD_ECOLOGY_QUANTIZATION = ${QUANTIZATION};

export const WORLD_ECOLOGY_KIND_NAMES = ${JSON.stringify(KINDS)} as const;
export type WorldEcologyKind = (typeof WORLD_ECOLOGY_KIND_NAMES)[number];

export const WORLD_ECOLOGY_POINTS = new Int16Array([
${formatPacked(packed)}
]);
`;

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(scriptDirectory, "../src/game/world-ecology-data.ts");
writeFileSync(outputPath, output, "utf8");
console.log(
  `Generated ${packed.length / POINT_STRIDE} ecology points across ${cellCountX} × ${cellCountZ} cells.`,
);

function addPoint(kind, x, z, random, scale) {
  packed.push(
    KIND[kind],
    Math.round(x * QUANTIZATION),
    Math.round(z * QUANTIZATION),
    Math.round(random() * 255),
    Math.round(scale * QUANTIZATION),
  );
}

function choosePrimaryKind(biome, latitude, random) {
  const roll = random();
  const absoluteLatitude = Math.abs(latitude);

  if (biome.mountain > 0.64 && roll < 0.68) {
    if (absoluteLatitude > 26 || biome.mountain > 0.84) {
      return "mountain-alpine";
    }
    return biome.desert > 0.34 ? "mountain-dry" : "mountain-green";
  }

  if (biome.desert > 0.58) {
    if (roll < 0.54) {
      return "dune";
    }
    if (roll < 0.78) {
      return "rock";
    }
    if (roll < 0.92) {
      return "acacia";
    }
    return "adobe";
  }

  if (absoluteLatitude > 67) {
    return roll < 0.7 ? "rock" : "pine";
  }

  if (roll < 0.12) {
    if (biome.mountain > 0.42 || absoluteLatitude > 51) {
      return "chalet";
    }
    if (biome.tropical > 0.48) {
      return "villa";
    }
    return biome.humidity < 0.28 ? "adobe" : "townhouse";
  }

  if (biome.tropical > 0.55) {
    return roll < 0.72 ? "palm" : "broadleaf";
  }
  if (biome.mountain > 0.38 || absoluteLatitude > 50) {
    return roll < 0.72 ? "pine" : "rock";
  }
  if (biome.humidity > 0.5) {
    return "broadleaf";
  }
  if (absoluteLatitude < 39 && biome.humidity > 0.28) {
    return roll < 0.58 ? "cypress" : "broadleaf";
  }
  return roll < 0.62 ? "broadleaf" : "rock";
}

function primaryScale(kind, random) {
  if (kind.startsWith("mountain")) {
    return 0.78 + random() * 0.48;
  }
  if (kind === "dune") {
    return 0.7 + random() * 0.42;
  }
  if (kind === "rock") {
    return 0.58 + random() * 0.38;
  }
  if (["townhouse", "villa", "chalet", "adobe"].includes(kind)) {
    return 0.68 + random() * 0.34;
  }
  return 0.62 + random() * 0.36;
}

function isTree(kind) {
  return ["broadleaf", "pine", "cypress", "palm", "acacia"].includes(kind);
}

function sampleBiome(longitude, latitude) {
  const broadNoise = fractalNoise(longitude * 0.055, latitude * 0.07, 17);
  const tropical = Math.max(
    regionMask(longitude, latitude, -80, -46, -18, 8, 7),
    regionMask(longitude, latitude, 8, 32, -12, 7, 6),
    regionMask(longitude, latitude, 94, 145, -12, 24, 7),
  );
  const temperate = Math.max(
    regionMask(longitude, latitude, -12, 32, 42, 63, 8),
    regionMask(longitude, latitude, -130, -65, 40, 60, 9),
    regionMask(longitude, latitude, 102, 150, 22, 50, 8),
  );
  const desert = clamp(
    Math.max(
      regionMask(longitude, latitude, -18, 38, 13, 35, 5),
      regionMask(longitude, latitude, 34, 63, 12, 32, 5),
      regionMask(longitude, latitude, 112, 151, -39, -17, 6),
      regionMask(longitude, latitude, 12, 30, -31, -16, 5),
      regionMask(longitude, latitude, 82, 117, 35, 49, 5),
      regionMask(longitude, latitude, -122, -101, 24, 39, 5),
      regionMask(longitude, latitude, -76, -66, -29, -13, 4),
    ) *
      (0.82 + broadNoise * 0.28),
    0,
    1,
  );
  const mountain = mountainStrength(longitude, latitude);
  const humidity = clamp(
    0.22 + tropical * 0.78 + temperate * 0.48 + broadNoise * 0.27 - desert * 0.75,
    0,
    1,
  );
  return { desert, humidity, mountain, tropical };
}

function mountainStrength(longitude, latitude) {
  const andesLongitude = -70.5 + (latitude + 20) * 0.035;
  const rockiesLongitude = -111 + (latitude - 42) * -0.45;
  return clamp(
    Math.max(
      ridgeMask(longitude, latitude, andesLongitude, -57, 12, 2.8),
      ridgeMask(longitude, latitude, rockiesLongitude, 28, 63, 4.2),
      ridgeMask(longitude, latitude, 7 + (latitude - 45) * 4.2, 43, 49, 2.4),
      ridgeMask(longitude, latitude, 87 + (latitude - 29) * 2.4, 25, 35, 5.2),
      ridgeMask(longitude, latitude, 51 + (latitude - 31) * -1.7, 24, 40, 4.3),
      ridgeMask(longitude, latitude, 37 + (latitude + 3) * 0.25, -20, 13, 4),
      ridgeMask(longitude, latitude, 145, -44, -11, 3.8),
    ),
    0,
    1,
  );
}

function ridgeMask(longitude, latitude, ridgeLongitude, minLatitude, maxLatitude, width) {
  return (
    smoothWindow(latitude, minLatitude, maxLatitude, 4) *
    Math.exp(-Math.pow((longitude - ridgeLongitude) / width, 2))
  );
}

function regionMask(
  longitude,
  latitude,
  minLongitude,
  maxLongitude,
  minLatitude,
  maxLatitude,
  feather,
) {
  return (
    smoothWindow(longitude, minLongitude, maxLongitude, feather) *
    smoothWindow(latitude, minLatitude, maxLatitude, feather)
  );
}

function smoothWindow(value, minimum, maximum, feather) {
  const enter = smoothstep(value, minimum - feather, minimum + feather);
  const exit = 1 - smoothstep(value, maximum - feather, maximum + feather);
  return enter * exit;
}

function smoothstep(value, minimum, maximum) {
  const amount = clamp((value - minimum) / (maximum - minimum), 0, 1);
  return amount * amount * (3 - 2 * amount);
}

function fractalNoise(x, y, seed) {
  let amplitude = 0.58;
  let frequency = 1;
  let value = 0;
  let total = 0;
  for (let octave = 0; octave < 4; octave += 1) {
    value += valueNoise(x * frequency, y * frequency, seed + octave * 101) * amplitude;
    total += amplitude;
    amplitude *= 0.5;
    frequency *= 2.03;
  }
  return value / total;
}

function valueNoise(x, y, seed) {
  const x0 = Math.floor(x);
  const y0 = Math.floor(y);
  const tx = x - x0;
  const ty = y - y0;
  const sx = tx * tx * (3 - 2 * tx);
  const sy = ty * ty * (3 - 2 * ty);
  const top = lerp(
    coordinateNoise(x0, y0, seed),
    coordinateNoise(x0 + 1, y0, seed),
    sx,
  );
  const bottom = lerp(
    coordinateNoise(x0, y0 + 1, seed),
    coordinateNoise(x0 + 1, y0 + 1, seed),
    sx,
  );
  return lerp(top, bottom, sy);
}

function coordinateNoise(x, y, seed) {
  let value = Math.imul(x, 374761393) + Math.imul(y, 668265263) + seed * 1447;
  value = Math.imul(value ^ (value >>> 13), 1274126177);
  return ((value ^ (value >>> 16)) >>> 0) / 4294967295;
}

function isLand(longitude, latitude) {
  return landRings.some((land) => {
    if (
      longitude < land.minLongitude ||
      longitude > land.maxLongitude ||
      latitude < land.minLatitude ||
      latitude > land.maxLatitude
    ) {
      return false;
    }
    return isPointInsideRing(longitude, latitude, land.ring);
  });
}

function isPointInsideRing(x, y, ring) {
  let inside = false;
  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
    const [currentX, currentY] = ring[index];
    const [previousX, previousY] = ring[previous];
    const crosses =
      currentY > y !== previousY > y &&
      x <
        ((previousX - currentX) * (y - currentY)) /
          (previousY - currentY) +
          currentX;
    if (crosses) {
      inside = !inside;
    }
  }
  return inside;
}

function geometryToOuterRings(geometry) {
  if (!geometry) {
    return [];
  }
  if (geometry.type === "Polygon") {
    return geometry.coordinates[0] ? [geometry.coordinates[0]] : [];
  }
  if (geometry.type === "MultiPolygon") {
    return geometry.coordinates
      .map((polygon) => polygon[0])
      .filter(Boolean);
  }
  return [];
}

function latitudeToMercator(latitude) {
  const radians = (clamp(latitude, MIN_LATITUDE, MAX_LATITUDE) * Math.PI) / 180;
  return (Math.log(Math.tan(Math.PI / 4 + radians / 2)) * 180) / Math.PI;
}

function mercatorToLatitude(mercatorLatitude) {
  const radians =
    2 * Math.atan(Math.exp((mercatorLatitude * Math.PI) / 180)) - Math.PI / 2;
  return (radians * 180) / Math.PI;
}

function hashCell(x, z) {
  return (Math.imul(x + 1, 73856093) ^ Math.imul(z + 1, 19349663)) >>> 0;
}

function mulberry32(seed) {
  return () => {
    let value = (seed += 0x6d2b79f5);
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

function formatPacked(values) {
  const rows = [];
  for (let index = 0; index < values.length; index += 50) {
    rows.push(`  ${values.slice(index, index + 50).join(", ")},`);
  }
  return rows.join("\n");
}

function lerp(from, to, amount) {
  return from + (to - from) * amount;
}

function clamp(value, minimum, maximum) {
  return Math.max(minimum, Math.min(maximum, value));
}
